using MathHub.Api.Endpoints;
using MathHub.Api.Middleware;
using MathHub.Modules.Assessment.Application;
using MathHub.Modules.Assessment.Domain;
using MathHub.Modules.Groups.Application;
using MathHub.SharedKernel.Application;
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<BusinessRuleExceptionHandler>();
builder.Services.AddSingleton<IClock, SystemClock>();
builder.Services.AddSingleton<IScoringEngine, EloScoringEngine>();
builder.Services.AddScoped<ScorePreviewService>();
builder.Services.AddScoped<IGroupMatchingStrategy, DeltaMatchingStrategy>();
var app = builder.Build();
app.UseExceptionHandler();
app.MapGet("/health", () => Results.Ok(new { status = "healthy", stage = "lab4-foundation" }));
app.MapAssessmentPreview();
app.Run();
